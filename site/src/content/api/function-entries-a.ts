const FNS_IMPORT = '@sdcorejs/utils/fns' as const;

type FunctionSpec = Omit<MemberSpec, 'en' | 'vi'> & {
  readonly en: string;
  readonly vi: string;
};

const parameter = (
  name: string,
  type: string,
  en: string,
  vi: string,
  options: { readonly optional?: boolean; readonly defaultValue?: string } = {},
): ParameterSpec => ({ name, type, en, vi, ...options });

const createFunctionEntry = (pageId: PageId, spec: FunctionSpec): ApiEntry => {
  const { name: symbol, ...details } = spec;
  return createEntry({
    symbol,
    kind: 'function',
    pageId,
    importPath: FNS_IMPORT,
    ...details,
  });
};

const namespaceSignature = (name: string, members: readonly { readonly signature: string }[]): string =>
  `const ${name}: {\n${members.map(member => `  ${member.signature};`).join('\n')}\n}`;

